// Command dor runs the server side of Dor: any subset of agents and, in local
// mode, an embedded NATS JetStream server.
package main

import (
	"errors"
	"fmt"
	"os"
)

func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, "dor:", err)
		os.Exit(1)
	}
}

func run(args []string) error {
	if len(args) == 0 {
		usage()
		return errors.New("missing command")
	}
	switch args[0] {
	case "run":
		return runCommand(args[1:])
	case "version", "--version", "-v":
		fmt.Println(version)
		return nil
	case "help", "--help", "-h":
		usage()
		return nil
	default:
		usage()
		return fmt.Errorf("unknown command %q", args[0])
	}
}

func usage() {
	fmt.Fprint(os.Stderr, `dor — a live map of the world's stories

Usage:
  dor run [flags]     run agents (and the embedded bus in local mode)
  dor version         print the version

Run "dor run -h" for flags.
`)
}
