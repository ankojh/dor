func TestPendingTTL(t *testing.T) {
	if got := DefaultBudget().PendingTTL.Std(); got != 15*time.Minute {
		t.Errorf("default pending_ttl = %v, want 15m", got)
	}
	// Omitted in a file: the default applies.
	b, err := LoadBudget(writeFile(t, "b.yaml", "daily_usd: 3\n"))
	if err != nil || b.PendingTTL.Std() != 15*time.Minute {
		t.Errorf("omitted: %v %v", b.PendingTTL, err)
	}
	// Loaded from YAML.
	b, err = LoadBudget(writeFile(t, "b.yaml", "pending_ttl: 30m\n"))
	if err != nil || b.PendingTTL.Std() != 30*time.Minute {
		t.Errorf("30m: %v %v", b.PendingTTL, err)
	}
	// Non-positive or malformed values are rejected.
	for _, body := range []string{"pending_ttl: 0s\n", "pending_ttl: -5m\n", "pending_ttl: soon\n"} {
		if _, err := LoadBudget(writeFile(t, "b.yaml", body)); err == nil {
			t.Errorf("%q must be rejected", body)
		}
	}
	// The committed file loads and carries the default.
	committed, err := LoadBudget("budget.yaml")
	if err != nil || committed.PendingTTL.Std() <= 0 {
		t.Errorf("committed budget.yaml: %v %v", committed.PendingTTL, err)
	}
}
