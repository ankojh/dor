func TestSaveThresholdsRoundTrip(t *testing.T) {
	p := filepath.Join(t.TempDir(), "out.yaml")
	in := DefaultThresholds()
	in.Classify.Accept = 0.85
	in.Plot.Primary = 0.7
	in.Relate.Accept = 0.55
	in.SelectedAt = "2026-12-01"
	in.Provisional = true
	if err := SaveThresholds(p, in); err != nil {
		t.Fatal(err)
	}
	raw, _ := os.ReadFile(p)
	if !strings.HasPrefix(string(raw), "# Generated by `make eval`") {
		t.Errorf("missing generated header: %q", string(raw)[:40])
	}
	if _, err := os.Stat(p + ".tmp"); err == nil {
		t.Error("temp file left behind")
	}
	out, err := LoadThresholds(p)
	if err != nil {
		t.Fatal(err)
	}
	if out != in {
		t.Errorf("round trip changed values:\n got %+v\nwant %+v", out, in)
	}
	if !out.Provisional {
		t.Error("provisional must survive the round trip")
	}
}

