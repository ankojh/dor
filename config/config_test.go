func TestLoadThresholdsFillsDefaults(t *testing.T) {
	p := writeFile(t, "t.yaml", "version: 1\nclassify:\n  accept: 0.82\n")
	th, err := LoadThresholds(p)
	if err != nil {
		t.Fatal(err)
	}
	if th.Classify.Accept != 0.82 {
		t.Errorf("classify.accept = %v", th.Classify.Accept)
	}
	d := DefaultThresholds()
	if th.Plot.Primary != d.Plot.Primary || th.Relate.Accept != d.Relate.Accept ||
		th.Match.Strictness != d.Match.Strictness || th.Targets != d.Targets || th.LabelSource != d.LabelSource {
		t.Errorf("omitted fields not defaulted: %+v", th)
	}
}

