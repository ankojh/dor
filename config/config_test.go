func writeFile(t *testing.T, name, body string) string {
	t.Helper()
	p := filepath.Join(t.TempDir(), name)
	if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
	return p
}

func TestCommittedConfigsLoad(t *testing.T) {
	th, err := LoadThresholds("thresholds.yaml")
	if err != nil {
		t.Fatalf("thresholds: %v", err)
	}
	if !th.Provisional || th.Classify.Accept != 0.70 || th.Plot.Primary != 0.60 || th.Plot.Party != 0.65 ||
		th.Relate.Accept != 0.60 || th.Match.Strictness != 0.80 {
		t.Errorf("unexpected committed thresholds: %+v", th)
	}
	if th.Targets.PlacePickAccuracy != 0.90 || th.Targets.RelationTypeAccuracy != 0.85 || th.Targets.ClaudeFallbackRate != 0.15 {
		t.Errorf("unexpected targets: %+v", th.Targets)
	}
	m, err := LoadModels("models.yaml")
	if err != nil {
		t.Fatalf("models: %v", err)
	}
	if m.Jev.Model != "typesafe/jev-1.14" || m.Claude.HaikuModel != "claude-haiku-5-5" || m.Claude.OpusModel != "claude-opus-5-5" {
		t.Errorf("unexpected models: %+v", m)
	}
	if m.Jev.Timeout.Std() != 30*time.Second || m.Claude.MinBackoff.Std() != 500*time.Millisecond {
		t.Errorf("durations not parsed: %v %v", m.Jev.Timeout, m.Claude.MinBackoff)
	}
	b, err := LoadBudget("budget.yaml")
	if err != nil {
		t.Fatalf("budget: %v", err)
	}
	if b.DailyUSD != 5 || b.ShedBriefAt != 0.8 || b.ShedWhyAt != 0.9 || b.ShedThematicAt != 0.95 || len(b.TokenBuckets) != 5 {
		t.Errorf("unexpected budget: %+v", b)
	}
}

