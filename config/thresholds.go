package config

import (
	"fmt"
	"os"
	"time"

	"go.yaml.in/yaml/v4"
)

// SampleCounts is the size of the labelled eval sets a threshold came from.
type SampleCounts struct {
	Articles int `yaml:"articles"`
	Pairs    int `yaml:"pairs"`
	Match    int `yaml:"match"`
}

// Thresholds are the answers' acceptance thresholds. Each question is
// calibrated separately because jev's probabilities are model-specific.
type Thresholds struct {
	Version     int          `yaml:"version"`
	Provisional bool         `yaml:"provisional"`
	LabelSource string       `yaml:"label_source"`
	SampleSize  int          `yaml:"sample_size"`
	Samples     SampleCounts `yaml:"samples"`
	SelectedAt  string       `yaml:"selected_at"`

	Classify struct {
		Accept float64 `yaml:"accept"`
	} `yaml:"classify"`
	Plot struct {
		Primary float64 `yaml:"primary"`
		Party   float64 `yaml:"party"`
	} `yaml:"plot"`
	Relate struct {
		Accept float64 `yaml:"accept"`
	} `yaml:"relate"`
	Match struct {
		Strictness float64 `yaml:"strictness"`
	} `yaml:"match"`
	Targets Targets `yaml:"targets"`
}

// Targets is the acceptance bar the threshold selection aims at.
type Targets struct {
	PlacePickAccuracy    float64 `yaml:"place_pick_accuracy"`
	RelationTypeAccuracy float64 `yaml:"relation_type_accuracy"`
	ClaudeFallbackRate   float64 `yaml:"claude_fallback_rate"`
}

// DefaultThresholds returns the plan's starting values, marked provisional.
// They are used when a config file is absent, and when eval runs against mock
// backends and must not select new values.
func DefaultThresholds() Thresholds {
	t := Thresholds{
		Version:     1,
		Provisional: true,
		LabelSource: "agent:deepseek-v4.1-flash (provisional)",
		SampleSize:  60,
		Samples:     SampleCounts{Articles: 30, Pairs: 30, Match: 20},
		SelectedAt:  "2026-11-20",
	}
	t.Classify.Accept = 0.70
	t.Plot.Primary = 0.60
	t.Plot.Party = 0.65
	t.Relate.Accept = 0.60
	t.Match.Strictness = 0.80
	t.Targets.PlacePickAccuracy = 0.90
	t.Targets.RelationTypeAccuracy = 0.85
	t.Targets.ClaudeFallbackRate = 0.15
	return t
}

// LoadThresholds reads config/thresholds.yaml, filling omitted fields with the
// plan's starting values.
func LoadThresholds(path string) (Thresholds, error) {
	t := DefaultThresholds()
	if err := readYAML(path, &t); err != nil {
		return Thresholds{}, err
	}
	if err := t.Validate(); err != nil {
		return Thresholds{}, fmt.Errorf("config: %s: %w", path, err)
	}
	return t, nil
}

// Validate checks ranges and fills derived fields. It fails loudly rather than
// silently clamping: a threshold outside [0,1] is a typo, not a default.
func (t *Thresholds) Validate() error {
	if t.SampleSize == 0 {
		t.SampleSize = t.Samples.Articles + t.Samples.Pairs + t.Samples.Match
	}
	if t.SelectedAt != "" {
		if _, err := time.Parse("2006-01-02", t.SelectedAt); err != nil {
			return fmt.Errorf("selected_at %q is not YYYY-MM-DD: %w", t.SelectedAt, err)
		}
	}
	checks := []struct {
		name  string
		value float64
	}{
		{"classify.accept", t.Classify.Accept},
		{"plot.primary", t.Plot.Primary},
		{"plot.party", t.Plot.Party},
		{"relate.accept", t.Relate.Accept},
		{"match.strictness", t.Match.Strictness},
		{"targets.place_pick_accuracy", t.Targets.PlacePickAccuracy},
		{"targets.relation_type_accuracy", t.Targets.RelationTypeAccuracy},
		{"targets.claude_fallback_rate", t.Targets.ClaudeFallbackRate},
	}
	for _, c := range checks {
		if c.value < 0 || c.value > 1 {
			return fmt.Errorf("%s = %v, want 0..1", c.name, c.value)
		}
	}
	if t.LabelSource == "" {
		return fmt.Errorf("label_source is empty")
	}
	return nil
}

// SaveThresholds writes thresholds back to config/thresholds.yaml. The file is
// generated after a live eval; comments in the hand-written file are replaced.
func SaveThresholds(path string, t Thresholds) error {
	if err := t.Validate(); err != nil {
		return err
	}
	body, err := yaml.Marshal(t)
	if err != nil {
		return fmt.Errorf("config: marshal thresholds: %w", err)
	}
	header := fmt.Sprintf("# Generated by `make eval` on %s from a live run.\n"+
		"# provisional: true means the set is small or agent-labelled; re-run with\n"+
		"# human labels before treating these as tuned values.\n", time.Now().UTC().Format(time.RFC3339))
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, append([]byte(header), body...), 0o644); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}
