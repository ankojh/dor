func TestPublishStoresMsgIDHeaderAndMergesHeaders(t *testing.T) {
	b := testBus(t, t.TempDir())
	defer b.Close()
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()

	if _, err := b.Publish(ctx, bus.SubjectEchoOut, []byte("x"),
		bus.WithMsgID("hdr-1"),
		bus.WithHeaders(nats.Header{bus.HeaderArticleID: {"art-1"}}),
		// A caller-supplied Nats-Msg-Id header must not override WithMsgID.
		bus.WithHeaders(nats.Header{bus.HeaderMsgID: {"bogus"}}),
	); err != nil {
		t.Fatal(err)
	}
	raw, err := b.Stream().GetLastMsgForSubject(ctx, bus.SubjectEchoOut)
	if err != nil {
		t.Fatal(err)
	}
	if got := raw.Header.Get(bus.HeaderMsgID); got != "hdr-1" {
		t.Errorf("stored Nats-Msg-Id = %q, want hdr-1", got)
	}
	if got := raw.Header.Get(bus.HeaderArticleID); got != "art-1" {
		t.Errorf("stored Dor-Article-Id = %q", got)
	}
}

func TestAutoGeneratedMsgIDsAreUnique(t *testing.T) {
	b := testBus(t, t.TempDir())
	defer b.Close()
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	for i := 0; i < 3; i++ {
		ack, err := b.Publish(ctx, bus.SubjectEchoOut, []byte("same payload"))
		if err != nil || ack.Duplicate {
			t.Fatalf("publish %d: dup=%v err=%v", i, ack != nil && ack.Duplicate, err)
		}
	}
}

