func TestConnectCustomOptionsAndBadWindow(t *testing.T) {
	ctx, cancel := context.WithTimeout(context.Background(), 20*time.Second)
	defer cancel()
	log := slog.New(slog.NewTextHandler(io.Discard, nil))
	if _, err := bus.Connect(ctx, bus.Options{
		ListenAddr: "127.0.0.1:0", StoreDir: t.TempDir(), Logger: log,
		DuplicateWindow: time.Hour, StreamMaxAge: time.Minute,
	}); err == nil {
		t.Fatal("duplicate window > max age accepted")
	}
	b, err := bus.Connect(ctx, bus.Options{
		ListenAddr: "127.0.0.1:0", StoreDir: t.TempDir(), Logger: log,
		MaxAckPending: 9, DuplicateWindow: 5 * time.Second, StreamMaxAge: time.Hour,
	})
	if err != nil {
		t.Fatal(err)
	}
	defer b.Close()
	if !b.Embedded() || !b.Connected() || b.MaxAckPending() != 9 {
		t.Errorf("embedded=%v connected=%v mac=%d", b.Embedded(), b.Connected(), b.MaxAckPending())
	}
	info, err := b.Stream().Info(ctx)
	if err != nil {
		t.Fatal(err)
	}
	if info.Config.Duplicates != 5*time.Second || info.Config.MaxAge != time.Hour {
		t.Errorf("custom stream config not applied: %+v", info.Config)
	}
	c, err := b.EnsureConsumer(ctx, bus.ConsumerOptions{Durable: "d", FilterSubject: bus.SubjectEchoIn})
	if err != nil {
		t.Fatal(err)
	}
	ci, _ := c.Info(ctx)
	if ci.Config.MaxAckPending != 9 || ci.Config.AckPolicy != jetstream.AckExplicitPolicy {
		t.Errorf("consumer config: %+v", ci.Config)
	}
}

// Port 0 must give each embedded server its own port (parallel packages).
func TestConcurrentEmbeddedBusesGetDistinctPorts(t *testing.T) {
	a := testBus(t, t.TempDir())
	defer a.Close()
	b := testBus(t, t.TempDir())
	defer b.Close()
	if a.URL() == b.URL() {
		t.Fatalf("both buses on %s", a.URL())
	}
	if a.URL() == "nats://127.0.0.1:4222" {
		t.Fatal("port 0 fell back to the default 4222")
	}
}

func TestIsPipelineSubjectAndSubjectsCovered(t *testing.T) {
	for _, s := range []string{
		bus.SubjectArticleRaw, bus.SubjectArticleRawPriority, bus.SubjectArticleClean, bus.SubjectArticlePlace,
		bus.SubjectArticleClass, bus.SubjectArticleVec, bus.SubjectLinkChanged, bus.SubjectArticlePlaced,
		bus.SubjectMatchAlert, bus.SubjectDeltaOut, bus.SubjectEchoIn, bus.SubjectEchoOut,
		bus.StoryChangedSubject("x"), bus.MatchFilterSubject("c"),
	} {
		if !bus.IsPipelineSubject(s) {
			t.Errorf("%q not recognised as pipeline subject", s)
		}
	}
	if bus.IsPipelineSubject("other.thing") {
		t.Error("other.thing recognised")
	}
	if got := bus.StoryShard("anything"); got < 0 || got >= bus.StoryShardCount {
		t.Errorf("shard out of range: %d", got)
	}
	seen := map[int]bool{}
	for i := 0; i < 2000; i++ {
		seen[bus.StoryShard(string(rune('a'+i%26))+time.Duration(i).String())] = true
	}
	if len(seen) != bus.StoryShardCount {
		t.Errorf("only %d of %d shards used across 2000 ids", len(seen), bus.StoryShardCount)
	}
}
